"""Generate a SYNTHETIC loan book for run 1, to demo the join, exclusions and staleness check.

Sarah won't share real loan data until procurement signs, so this is made up, deterministically (fixed seed).
Run from the repo root:  python3 runs/run-1/data/make_loan_book.py
"""
import json, os
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
rng = np.random.default_rng(20261101)
spectra = pd.read_csv(os.path.join(HERE, 'spectra_portfolio_export.csv'))

EXPORT_AS_AT = '2026-06-30'     # Spectra export date (Q2), assumed for the demo
BOOK_AS_AT = '2026-09-30'       # loan book date (Q3): the export is a quarter older

book = spectra[['loan_id', 'loan_type', 'balance_gbp', 'origination_year']].copy()
n = len(book)
# origination date from the loan system; ~3% differ by a year from Spectra's origination_year
shift = np.where(rng.random(n) < 0.03, rng.choice([-1, 1], n), 0)
year = (book.origination_year + shift).clip(upper=2025)
book['origination_date'] = [f'{y}-{m:02d}-15' for y, m in zip(year, rng.integers(1, 13, n))]
term = np.where(book.loan_type == 'Commercial real estate', rng.integers(5, 16, n), rng.integers(20, 31, n))
book['maturity_date'] = [f'{int(o[:4]) + t}-{o[5:7]}-15' for o, t in zip(book.origination_date, term)]
status = rng.choice(['performing', 'in default', 'redeemed'], n, p=[0.97, 0.015, 0.015])
book['status'] = status
book['redeemed_date'] = np.where(status == 'redeemed', '2026-08-31', '')
# ~1% of Spectra loans missing from the loan book, plus 6 loan-book loans with no Spectra row
book = book.drop(book.sample(frac=0.01, random_state=7).index)
extra = pd.DataFrame({'loan_id': [f'L9{i:05d}' for i in range(6)], 'loan_type': 'Residential mortgage',
                      'balance_gbp': rng.integers(80_000, 300_000, 6), 'origination_year': 2025,
                      'origination_date': '2025-11-15', 'maturity_date': '2050-11-15', 'status': 'performing', 'redeemed_date': ''})
book = pd.concat([book, extra], ignore_index=True).drop(columns='origination_year')
book.to_csv(os.path.join(HERE, 'loan_book_synthetic.csv'), index=False)

json.dump({
    'spectra_export': {'file': 'spectra_portfolio_export.csv', 'as_at': EXPORT_AS_AT, 'note': 'practice data (synthetic)'},
    'loan_book': {'file': 'loan_book_synthetic.csv', 'as_at': BOOK_AS_AT, 'note': 'SYNTHETIC, generated by make_loan_book.py'},
    'scenario_names': {'central': 'ssp245', 'severe': 'ssp585', 'low': 'ssp126', 'note': 'INFERRED mapping, to confirm'},
}, open(os.path.join(HERE, 'manifest.json'), 'w'), indent=2)
print(len(book), 'loan-book rows;', book.status.value_counts().to_dict())
